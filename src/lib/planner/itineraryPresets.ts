function definePreset(
  typeKey: ItineraryPresetType,
  key: string,
  headline: string,
  description: string,
  days: Array<[number, string, string, string[]]>,
): PresetItinerary {
  return {
    key,
    typeKey,
    headline,
    description,
    days: days.map(([day, title, dayDescription, spots]) => ({
      day,
      title,
      description: dayDescription,
      spots,
    })),
  };
}

