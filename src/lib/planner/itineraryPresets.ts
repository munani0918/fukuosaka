function withPresetHints(preset: PresetItinerary, city: "fukuoka" | "osaka"): PresetItinerary {
  const hints = PRESET_HINTS_BY_CITY[city][preset.typeKey];
  return {
    ...preset,
    tourKeywords: hints.tourKeywords,
    stayAreaHints: hints.stayAreaHints,
  };
}

function isPresetStyle(style: string): style is PresetStyle {
  return PRESET_STYLE_ORDER.includes(style as PresetStyle);
}

export function normalizeItineraryPresetType(styles: string[] = []): ItineraryPresetType {
  const selected = Array.from(new Set(styles.filter(isPresetStyle))).sort(
    (a, b) => PRESET_STYLE_ORDER.indexOf(a) - PRESET_STYLE_ORDER.indexOf(b),
  );

  if (selected.length === 0) {
    return "standard";
  }

  if (selected.length === 1) {
    return selected[0];
  }

  return `${selected[0]}_${selected[1]}` as ItineraryPresetType;
}

export const normalizeFukuokaPresetType = normalizeItineraryPresetType;
export const normalizeFukuokaTwoNightPresetType = normalizeFukuokaPresetType;

export function getCityItineraryPreset(input: {
  city: "fukuoka" | "osaka";
  nights: number;
  days: number;
  travelStyles: string[];
}) {
  const presets = PRESETS_BY_CITY[input.city][input.nights];
  if (!presets || input.days !== input.nights + 1) {
    return null;
  }

  const typeKey = normalizeItineraryPresetType(input.travelStyles);
  return withPresetHints(presets[typeKey] ?? presets.standard, input.city);
}

export function getFukuokaItineraryPreset(input: {
  city: "fukuoka" | "osaka";
  nights: number;
  days: number;
  travelStyles: string[];
}) {
  if (input.city !== "fukuoka") {
    return null;
  }

  return getCityItineraryPreset(input);
}

